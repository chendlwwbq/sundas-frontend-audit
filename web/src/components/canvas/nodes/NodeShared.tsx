export type NodeContentRendererProps = {
    node: CanvasNodeData;
    theme: (typeof canvasThemes)[keyof typeof canvasThemes];
    isEditingContent: boolean;
    textareaRef: RefObject<HTMLTextAreaElement | null>;
    isBatchRoot: boolean;
    batchCount: number;
    batchExpanded: boolean;
    scale: number;
    renderNodeContent?: (node: CanvasNodeData) => ReactNode;
    onContentChange: (nodeId: string, content: string) => void;
    onStopEditing: () => void;
    mentionReferences: CanvasResourceReference[];
    onRetry?: (node: CanvasNodeData) => void;
    onToggleBatch?: () => void;
    onSetBatchPrimary?: (itemId: string) => void;
    onDuplicateBatchImage?: (imageId: string) => void;
    onDownloadBatchImage?: (imageId: string) => void;
    onRetryBatchImage?: (imageId: string) => void;
    onDeleteBatchImage?: (imageId: string) => void;
    onViewBatchImage?: (imageId: string) => void;
    groupChildCount: number;
};

export function useNodeImagePreview(storageKey?: string, content?: string) {
    const cloud = useMediaPreview(content);
    const getPreview = useCallback(() => previewUrlFor(storageKey), [storageKey]);
    const preview = useSyncExternalStore(subscribeImagePreviews, getPreview, () => undefined);
    useEffect(() => {
        void ensureImagePreview(storageKey);
    }, [storageKey]);
    // Wait for the cloud derivative at small display sizes; magnification still selects the original.
    return preview || cloud.url || (cloud.cloud && !cloud.error ? "data:image/gif;base64,R0lGODlhAQABAAD/ACwAAAAAAQABAAACADs=" : undefined);
}

